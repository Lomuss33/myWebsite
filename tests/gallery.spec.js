import {test, expect} from '@playwright/test'
import {readFileSync} from 'node:fs'

const art = JSON.parse(readFileSync('public/data/sections/my-art.json', 'utf8'))

async function openArt(page, width, height, language = 'en', theme = 'dark') {
    await page.addInitScript(({language, theme}) => {
        localStorage.setItem('storage-preferences', JSON.stringify({preferredLanguage: language, preferredTheme: theme, preferredCursorMode: 'system'}))
    }, {language, theme})
    await page.setViewportSize({width, height})
    await page.goto('/#my-art', {waitUntil: 'domcontentloaded'})
    await expect(page.locator('#article-2-section-my-art')).toBeVisible()
}

for(const [width,height,language,theme] of [[390,844,'hr','light'],[1366,768,'en','dark']]) {
    test(`gallery uses one viewer for every album and entry point: ${width} ${language}/${theme}`, async ({page}) => {
        await openArt(page, width, height, language, theme)
        await page.locator('#article-1-section-my-art .article-timeline-see-more-button').click()
        const modal = page.locator('#gallery-modal')
        for(const articleId of [1,2]) {
            const items = page.locator(`#article-${articleId}-section-my-art .article-timeline-items > li`)
            const albums = [...art.articles[articleId - 1].items].sort((a,b) => (a.display_order ?? 0) - (b.display_order ?? 0))
            await expect(items).toHaveCount(albums.length)
            for(let index = 0; index < albums.length; index++) {
                const triggers = items.nth(index).locator('a[href="#gallery:open"]:visible')
                expect(await triggers.count()).toBeGreaterThan(0)
                for(let entry = 0; entry < await triggers.count(); entry++) {
                    const trigger = triggers.nth(entry)
                    await trigger.click()
                    await expect(modal).toHaveJSProperty('open', true)
                    await expect(modal.locator('.gallery-swiper')).toHaveClass(/swiper-horizontal/)
                    await expect(modal.locator('.swiper-slide')).toHaveCount(albums[index].preview.screenshots.length)
                    await expect(modal.locator('output')).toHaveText(`1 / ${albums[index].preview.screenshots.length}`)
                    await expect(modal.locator('.gallery-close')).toBeFocused()
                    await modal.locator('.gallery-close').click()
                    await expect(modal).toHaveCount(0)
                    await expect(trigger).toBeFocused()
                    await expect(page).toHaveURL(/#my-art$/)
                    await expect(page.locator('html')).not.toHaveClass(/gallery-modal-open/)
                }
            }
        }
    })
}

test('gallery supports keyboard, zoom, Back, Escape, backdrop and scroll restoration', async ({page}) => {
    await openArt(page, 1366, 768, 'de', 'light')
    const trigger = page.locator('#article-2-section-my-art .digital-expression-layer-stack__link').first()
    await trigger.scrollIntoViewIfNeeded()
    const scrollers = () => page.evaluate(() => [document.scrollingElement, ...document.querySelectorAll('#section-my-art, #section-my-art .section-content, #section-my-art .section-content-wrapper')].map(e => e.scrollTop))
    const scrollBefore = await scrollers()
    await trigger.click()
    const modal = page.locator('#gallery-modal')
    await expect(modal).toHaveJSProperty('open', true)
    await expect(modal).toHaveAccessibleName('AI Prompt 01')
    await expect(modal.locator('h2')).toHaveText('AI Prompt 01')
    await expect(modal.locator('.swiper-slide-active img')).toHaveAttribute('alt', 'AI Prompt 01 — 1 / 4')
    // Preloaded neighbours keep their own titles, independent of the active heading.
    await expect(modal.locator('.swiper-slide-next img')).toHaveAttribute('alt', 'AI Prompt 02 — 2 / 4')
    await expect(modal.locator('.gallery-next')).toHaveAttribute('aria-label', 'Nächstes Bild')
    await page.keyboard.press('ArrowRight')
    await expect(modal.locator('output')).toHaveText('2 / 4')
    await expect(modal).toHaveAccessibleName('AI Prompt 02')
    await expect(modal.locator('h2')).toHaveText('AI Prompt 02')
    await expect(modal.locator('.swiper-slide-active img')).toHaveAttribute('alt', 'AI Prompt 02 — 2 / 4')
    await page.keyboard.press('d')
    await expect(modal.locator('output')).toHaveText('3 / 4')
    await page.keyboard.press('a')
    await expect(modal.locator('output')).toHaveText('2 / 4')
    await page.keyboard.press('D')
    await expect(modal.locator('output')).toHaveText('3 / 4')
    await page.keyboard.press('A')
    await expect(modal.locator('output')).toHaveText('2 / 4')
    await modal.locator('.gallery-next').click()
    await expect(modal.locator('output')).toHaveText('3 / 4')
    await modal.locator('.gallery-previous').click()
    await expect(modal.locator('output')).toHaveText('2 / 4')
    await page.keyboard.press('ArrowLeft')
    await expect(modal.locator('output')).toHaveText('1 / 4')
    await expect(modal.locator('h2')).toHaveText('AI Prompt 01')
    await expect.poll(() => modal.locator('.swiper-slide-active img').evaluate(e => e.complete && e.naturalWidth > 0)).toBe(true)
    await modal.locator('.gallery-zoom').click()
    await expect(modal.locator('.gallery-zoom')).toHaveAttribute('aria-pressed', 'true')
    await modal.locator('.gallery-zoom').click()
    await expect(modal.locator('.gallery-zoom')).toHaveAttribute('aria-pressed', 'false')
    await page.goBack()
    await expect(modal).toHaveCount(0)
    await expect(trigger).toBeFocused()
    expect(await scrollers()).toEqual(scrollBefore)
    await trigger.click()
    await expect(modal).toHaveJSProperty('open', true)
    await page.keyboard.press('Escape')
    await expect(modal).toHaveCount(0)
    await trigger.click()
    await expect(modal).toHaveJSProperty('open', true)
    // This portrait leaves empty space at the edge of the image stage.
    await modal.locator('.gallery-stage').click({position: {x: 4, y: 4}})
    await expect(modal).toHaveCount(0)
    expect(await scrollers()).toEqual(scrollBefore)
    await trigger.click()
    await expect(modal).toHaveJSProperty('open', true)
    await modal.locator('.gallery-next').focus()
    await page.keyboard.press('Space')
    await expect(modal).toHaveCount(0)
    await expect(page).toHaveURL(/#my-art$/)
    await expect(trigger).toBeFocused()
    expect(await scrollers()).toEqual(scrollBefore)
})

test('gallery touch swipes navigate, pinch zoom preserves the viewer, and vertical swipe closes', async ({page, browserName}) => {
    test.skip(browserName !== 'chromium', 'Native touch injection uses Chromium CDP')
    await openArt(page, 390, 844, 'tr', 'dark')
    const trigger = page.locator('#article-2-section-my-art .digital-expression-layer-stack__link').first()
    await trigger.click()
    const modal = page.locator('#gallery-modal')
    await expect(modal).toHaveJSProperty('open', true)
    await expect.poll(() => modal.locator('.swiper-slide-active img').evaluate(e => e.complete && e.naturalWidth > 0)).toBe(true)
    const cdp = await page.context().newCDPSession(page)
    const touch = (type, points) => cdp.send('Input.dispatchTouchEvent', {type, touchPoints: points.map(([x,y],id) => ({x,y,id}))})
    await touch('touchStart', [[320,400]])
    for(const x of [280,230,170,100,55]) await touch('touchMove', [[x,400]])
    await touch('touchEnd', [])
    await expect(modal.locator('output')).toHaveText('2 / 4')
    await expect(modal).toHaveJSProperty('open', true)
    await touch('touchStart', [[155,400],[235,400]])
    for(const offset of [50,65,90,115]) await touch('touchMove', [[195-offset,400],[195+offset,400]])
    await touch('touchEnd', [])
    await expect(modal.locator('.gallery-zoom')).toHaveAttribute('aria-pressed', 'true')
    await expect(modal).toHaveJSProperty('open', true)
    await expect(modal.locator('output')).toHaveText('2 / 4')
    await touch('touchStart', [[195,350]])
    for(const y of [390,440,490]) await touch('touchMove', [[195,y]])
    await touch('touchEnd', [])
    await expect(modal).toHaveJSProperty('open', true)
    await modal.locator('.gallery-zoom').click()
    await expect(modal.locator('.gallery-zoom')).toHaveAttribute('aria-pressed', 'false')
    await touch('touchStart', [[195,350]])
    for(const y of [390,430,480,530]) await touch('touchMove', [[195,y]])
    await touch('touchEnd', [])
    await expect(modal).toHaveCount(0)
    await expect(page).toHaveURL(/#my-art$/)
})

test('gallery stays closable while images load or fail, including single-image albums', async ({page}) => {
    await openArt(page, 320, 568)
    await page.route('**/images/**', route => route.abort())
    await page.locator('#article-1-section-my-art .article-timeline-items > li').nth(1).locator('a[href="#gallery:open"]:visible').first().click()
    const modal = page.locator('#gallery-modal')
    await expect(modal).toHaveJSProperty('open', true)
    await expect(modal.locator('output')).toHaveText('1 / 1')
    await expect(modal.locator('.gallery-next')).toBeDisabled()
    await expect(modal.locator('.gallery-previous')).toBeDisabled()
    await expect(modal.locator('.gallery-image-state')).toHaveText('Image unavailable')
    await expect(modal.locator('.gallery-zoom')).toBeDisabled()
    await page.keyboard.press('Escape')
    await expect(modal).toHaveCount(0)
})

test('gallery stays on its page after repeated close requests', async ({page}) => {
    await openArt(page, 390, 844)
    // Give the viewer a real preceding site route, as when arriving from Home.
    await page.evaluate(() => {
        history.replaceState({sectionId: 'about'}, '', '#about')
        history.pushState({sectionId: 'my-art'}, '', '#my-art')
    })
    const trigger = page.locator('#article-2-section-my-art .digital-expression-layer-stack__link').first()
    await trigger.click()
    const modal = page.locator('#gallery-modal')
    await expect(modal).toHaveJSProperty('open', true)
    await modal.locator('.gallery-close').evaluate(button => {
        button.click()
        button.click()
        button.click()
    })
    await expect(modal).toHaveCount(0)
    await expect(page).toHaveURL(/#my-art$/)
    await expect(trigger).toBeFocused()
    await trigger.click()
    await expect(modal).toHaveJSProperty('open', true)
    await page.goBack()
    await expect(modal).toHaveCount(0)
    await expect(page).toHaveURL(/#my-art$/)
})

test('gallery supports double-tap zoom and retains the active image on rotation', async ({page}) => {
    await openArt(page, 390, 844)
    await page.locator('#article-2-section-my-art .digital-expression-layer-stack__link').first().click()
    const modal = page.locator('#gallery-modal')
    const image = modal.locator('.swiper-slide-active img')
    await expect.poll(() => image.evaluate(e => e.complete && e.naturalWidth > 0)).toBe(true)
    await image.dblclick()
    await expect(modal.locator('.gallery-zoom')).toHaveAttribute('aria-pressed', 'true')
    await modal.locator('.gallery-zoom').click()
    await modal.locator('.gallery-next').click()
    await expect(modal.locator('output')).toHaveText('2 / 4')
    await page.setViewportSize({width: 844, height: 390})
    await expect(modal.locator('output')).toHaveText('2 / 4')
    await expect(modal.locator('.gallery-close')).toBeInViewport()
    await page.keyboard.press('Escape')
    await expect(modal).toHaveCount(0)
})

test('gallery supports animated navigation, live reduced motion and keyboard focus containment', async ({page}) => {
    await page.emulateMedia({reducedMotion: 'no-preference'})
    await openArt(page, 568, 320)
    const trigger = page.locator('#article-2-section-my-art .digital-expression-layer-stack__link').first()
    await trigger.click()
    const modal = page.locator('#gallery-modal')
    await expect(modal.locator('.gallery-close')).toBeFocused()
    // Forward and reverse tabbing must stay inside the open viewer.
    for(const key of ['Tab', 'Tab', 'Tab', 'Shift+Tab', 'Shift+Tab', 'Shift+Tab']) {
        await page.keyboard.press(key)
        await expect.poll(() => modal.evaluate(dialog => dialog.contains(document.activeElement))).toBe(true)
    }
    // Reaching an album edge by clicking must leave shortcuts usable even
    // though the button that had focus becomes disabled.
    for(let index = 0; index < 3; index++) await modal.locator('.gallery-next').click()
    await expect(modal.locator('.gallery-next')).toBeDisabled()
    await page.keyboard.press('a')
    await expect(modal.locator('output')).toHaveText('3 / 4')
    await modal.locator('.gallery-previous').click()
    await modal.locator('.gallery-previous').click()
    await expect(modal.locator('.gallery-previous')).toBeDisabled()
    await page.keyboard.press('d')
    await expect(modal.locator('output')).toHaveText('2 / 4')
    await page.keyboard.press('a')
    for(const key of ['d', 'd', 'a', 'd', 'd', 'd']) await page.keyboard.press(key)
    await expect(modal.locator('output')).toHaveText('4 / 4')
    await expect(modal.locator('.gallery-next')).toBeDisabled()
    await expect.poll(() => modal.locator('.gallery-swiper').evaluate(element => element.swiper.animating)).toBe(false)
    await page.emulateMedia({reducedMotion: 'reduce'})
    for(const key of ['a', 'a', 'a', 'a']) await page.keyboard.press(key)
    await expect(modal.locator('output')).toHaveText('1 / 4')
    await expect(modal.locator('.gallery-previous')).toBeDisabled()
    await expect.poll(() => modal.locator('.gallery-swiper').evaluate(element => element.swiper.animating)).toBe(false)
    await expect(modal.locator('.gallery-close')).toBeInViewport()
    await expect(modal.locator('.gallery-next')).toBeInViewport()
    await page.keyboard.press('Space')
    await expect(modal).toHaveCount(0)
    await expect(trigger).toBeFocused()
})
